def __ROR1__(num, count, bits=8):
    return ((num >> count) | (num << (bits - count))) & ((0b1<<bits) - 1)

Arr = [0xDC, 0x3C, 0x0A, 0xBE, 0x75, 0xCB, 0x0A, 0x80, 0xF4, 0x4A, 
       0x8C, 0x86, 0xAA, 0xE4, 0xC3, 0x00]
EncryptedFlag = [0xA7, 0x4F, 0xB2, 0x70, 0x70, 0x50, 0xD8, 0xF9, 0xAB, 0xB1, 
                 0xFB, 0x78, 0x77, 0x87, 0x1D, 0xC3]
FLAG = ""

for i in range(0xf):
    FLAG += chr((EncryptedFlag[i] ^ Arr[i] ^ __ROR1__(Arr[i], 2)) - 0xa)

print(FLAG)